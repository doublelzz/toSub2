import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { createCdkStore } from "../src/cdk-store.mjs";
import { createCdkVault } from "../src/cdk-vault.mjs";
import { normalizeClientIp, clientIp } from "../src/cdk-security.mjs";

const root = await fs.mkdtemp(path.join(os.tmpdir(), "tosub2-cdk-store-"));
process.env.TOSUB2_ENCRYPTION_KEY = crypto.randomBytes(32).toString("base64");
process.env.TOSUB2_ADMIN_CDK = "test-admin-cdk-for-isolated-store-only";
const vault = await createCdkVault(root);
let store = await createCdkStore(root, vault);
try {
  const admin = store.authenticate(process.env.TOSUB2_ADMIN_CDK);
  assert.equal(admin.role, "admin");
  const created = store.generate({ count: 3, quota: 2, note: "synthetic" }, admin.id);
  const [first, second, source] = created;
  assert.equal(store.revealSecret(admin.id, admin.id), process.env.TOSUB2_ADMIN_CDK);
  assert.equal(store.revealSecret(first.id, first.id), first.secret);
  assert.equal(store.revealSecret(second.id, admin.id), second.secret);
  assert.throws(() => store.revealSecret(second.id, first.id), /只能查看当前/);
  assert.throws(() => store.rememberSecret(first.id, second.secret), /无效/);
  assert.equal(JSON.stringify(store.list()).includes(first.secret), false, "list remains masked");
  const session = store.createSession(first.id);
  assert.equal(store.session(session.secret).actor.id, first.id);
  assert.throws(() => store.switchWorkspace(store.session(session.secret), second.id), /无权/);
  const imported = store.prepareImport(first.id, "single", ["same@example.com"], { email: "same@example.com" }, "first");
  assert.equal(store.get(first.id).balance, 1);
  assert.equal(store.get(first.id).reserved, 1);
  assert.throws(() => store.mergePreview(second.id, first.secret), /未完成的导入/);
  store.finishImport(imported, { status: 201, data: { created: true } }, first.id);
  assert.equal(store.get(first.id).balance, 1);
  assert.equal(store.get(first.id).consumed, 1);
  const repeated = store.prepareImport(first.id, "single", ["same@example.com"], { email: "same@example.com" }, "first");
  assert.equal(repeated.status, "completed");
  assert.throws(() => store.prepareImport(first.id, "single", ["other@example.com"], { email: "other@example.com" }, "first"), /内容不同/);
  assert.equal(store.preview(first.id, ["same@example.com"]).charge, 0);
  assert.equal(store.preview(second.id, ["same@example.com"]).charge, 1);
  store.deleted(first.id, ["same@example.com"]);
  assert.equal(store.preview(first.id, ["same@example.com"]).charge, 0);
  store.topup(first.id, 10, "synthetic topup", "topup", admin.id);
  assert.equal(store.get(first.id).balance, 11);
  store.topup(first.id, 10, "synthetic topup", "topup", admin.id);
  assert.equal(store.get(first.id).balance, 11);
  assert.throws(() => store.mergePreview(second.id, first.secret), /曾消耗/);
  const quote = store.mergePreview(first.id, source.secret);
  const result = store.merge(first.id, source.secret, "merge", quote.fingerprint);
  assert.equal(result.cdk.balance, 13);
  assert.equal(store.get(source.id).status, "merged");
  assert.equal(store.authenticate(source.secret), null);
  assert.equal(store.merge(first.id, source.secret, "merge", quote.fingerprint).cdk.balance, 13);
  assert.throws(() => store.update(source.id, { status: "active" }, admin.id), /已融合/);
  store.saveSetting(first.id, "workspace", { apiKey: "synthetic-private-value" });
  assert.equal(store.setting(second.id, "workspace"), null);
  const raw = await fs.readFile(path.join(root, ".cdk", "cdk.sqlite"));
  assert.equal(raw.includes(Buffer.from("synthetic-private-value")), false);
  for (const secret of [first.secret, second.secret, process.env.TOSUB2_ADMIN_CDK]) assert.equal(raw.includes(Buffer.from(secret)), false, "CDKs are not stored as plaintext");
  for (let attempt = 0; attempt < 10; attempt += 1) {
    const attemptId = store.checkVerification("198.51.100.12");
    store.failedVerification("198.51.100.12", "login", "synthetic-invalid", attemptId);
  }
  assert.ok(store.activeBan("198.51.100.12"));
  assert.ok(store.events().some((event) => event.unread && event.count === 10));
  assert.throws(() => store.checkVerification("198.51.100.12"), /封禁/);
  assert.equal(normalizeClientIp("::ffff:198.51.100.12"), "198.51.100.12");
  assert.equal(normalizeClientIp("::ffff:c633:640c"), "198.51.100.12");
  assert.equal(clientIp({ socket: { remoteAddress: "198.51.100.12" }, headers: { "x-forwarded-for": "1.2.3.4" } }), "198.51.100.12");
  store.close(); store = await createCdkStore(root, vault);
  assert.equal(store.get(first.id).balance, 13);
  assert.equal(store.revealSecret(first.id, first.id), first.secret, "reveal survives restarting the store");
  const rotated = store.rotate(second.id, admin.id);
  assert.equal(store.revealSecret(second.id, second.id), rotated.secret, "reveal uses rotated CDK");
  assert.notEqual(rotated.secret, second.secret);
  store.saveSetting(first.id, "login-secret", null);
  assert.throws(() => store.revealSecret(first.id, first.id), (error) => error.code === "CDK_SECRET_UNAVAILABLE");
  store.rememberSecret(first.id, first.secret);
  assert.equal(store.revealSecret(first.id, first.id), first.secret, "legacy key can be verified and retained");
  assert.ok(store.activeBan("198.51.100.12"));
  store.update(first.id, { status: "disabled" }, admin.id);
  assert.equal(store.session(session.secret), null);
  console.log("cdk store passed (joint ownership, reservations, idempotency, merge eligibility, encrypted settings, persisted bans, session revocation)");
} finally {
  store.close(); await fs.rm(root, { recursive: true, force: true });
}
